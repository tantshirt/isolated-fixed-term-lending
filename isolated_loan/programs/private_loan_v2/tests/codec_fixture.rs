use serde_json::{json, Value};

fn key(n: u8) -> Pubkey {
    Pubkey::new_from_array([n; 32])
}

fn hex(v: &impl AnchorSerialize) -> String {
    let mut out = Vec::new();
    v.serialize(&mut out).unwrap();
    out.iter().map(|b| format!("{b:02x}")).collect()
}

