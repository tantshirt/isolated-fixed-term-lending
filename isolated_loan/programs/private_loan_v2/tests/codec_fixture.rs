#[test]
fn codec_fixture_matches() {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/codec-fixture.json");
    let built = build();
    if std::env::var("REGENERATE_FIXTURE").is_ok() {
        std::fs::write(path, serde_json::to_string_pretty(&built).unwrap() + "\n").unwrap();
    }
    let stored: Value = serde_json::from_str(&std::fs::read_to_string(path).expect("run with REGENERATE_FIXTURE=1 once")).unwrap();
    assert_eq!(stored, built);
}
